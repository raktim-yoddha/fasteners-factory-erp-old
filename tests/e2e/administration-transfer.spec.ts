import { expect,test } from '@playwright/test'
import { authenticateSampleUser } from './support/auth'

test('SAMPLE administration protects the last owner; imports reconcile retries and handoffs require approval',async ({ page }) => {
  const client=await authenticateSampleUser(page)
  await expect(page.getByLabel('Active company')).not.toHaveValue('')
  const companyId=await page.getByLabel('Active company').inputValue(),run=crypto.randomUUID().slice(0,8).toUpperCase()
  const user=await client.auth.getUser();if (user.error) throw new Error('SAMPLE identity unavailable')
  await page.getByRole('button',{ name: 'Administration',exact: true }).click()
  await page.getByLabel('Staff member').selectOption(user.data.user.id)
  await page.getByLabel('Active company access').uncheck()
  await page.getByLabel('Access change reason').fill('SAMPLE test last administrator guard')
  await page.getByRole('button',{ name: 'Confirm staff access',exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('keep at least one active administrator')
  await page.getByRole('button',{ name: 'Data transfer',exact: true }).click()
  const panel=page.getByRole('region',{ name: 'Data transfer' }),filename=`sample-items-${run}.csv`,sku=`SAMPLE-IMPORT-${run}`
  await panel.getByLabel('Import CSV file').setInputFiles({ name: filename,mimeType: 'text/csv',buffer: Buffer.from(`sku,description,base_uom\n${sku},SAMPLE imported item,kg\n`) })
  await expect(panel.getByRole('button',{ name: 'Preview import on server' })).toBeEnabled()
  await page.route('**/rest/v1/rpc/preview_data_import',async (route) => { const response=await route.fetch();expect(response.ok()).toBe(true);await route.abort('failed') },{ times: 1 })
  await panel.getByRole('button',{ name: 'Preview import on server' }).click()
  await expect(panel.getByRole('alert')).toContainText('could not be confirmed')
  await panel.getByRole('button',{ name: 'Preview import on server' }).click()
  await expect(panel.getByLabel('Import batch')).not.toHaveValue('')
  await expect(panel.getByRole('article',{ name: 'Import reconciliation' })).toContainText('1 input rows · 0 validation errors · 0 confirmed records')
  await panel.getByLabel('I reconciled these rows against the source and opening counts').check()
  await panel.getByLabel('Import approval reason').fill('SAMPLE reviewed input against source')
  await page.route('**/rest/v1/rpc/apply_data_import',async (route) => { const response=await route.fetch();expect(response.ok()).toBe(true);await route.abort('failed') },{ times: 1 })
  await panel.getByRole('button',{ name: 'Apply reviewed import' }).click()
  await expect(panel.getByRole('alert')).toContainText('could not be confirmed')
  await panel.getByRole('button',{ name: 'Apply reviewed import' }).click()
  await expect(panel.getByRole('article',{ name: 'Import reconciliation' })).toContainText('1 confirmed records')
  const imported=await client.from('items').select('id').eq('company_id',companyId).eq('sku',sku)
  expect(imported.error).toBeNull();expect(imported.data).toHaveLength(1)
  const batches=await client.from('import_batches').select('id,status').eq('company_id',companyId).eq('source_name',filename)
  expect(batches.error).toBeNull();expect(batches.data).toHaveLength(1)
  await panel.getByRole('button',{ name: 'Preview import on server' }).click()
  await expect(panel.getByRole('article',{ name: 'Import reconciliation' })).toContainText('1 validation errors')
  await expect(panel.getByRole('button',{ name: 'Apply reviewed import' })).toBeDisabled()
  await panel.getByRole('button',{ name: 'Accounting handoff',exact: true }).click()
  await panel.getByRole('button',{ name: 'Prepare accounting handoff',exact: true }).click()
  await expect(panel.getByRole('button',{ name: 'Download approved handoff CSV' })).toBeDisabled()
  await panel.getByLabel('I checked source events, signed returns and currency totals').check()
  await panel.getByLabel('Handoff approval reason').fill('SAMPLE checked recorded amounts and signed return events')
  await panel.getByRole('button',{ name: 'Approve accounting handoff',exact: true }).click()
  await expect(panel.getByRole('button',{ name: 'Download approved handoff CSV' })).toBeEnabled()
  const downloadEvent=page.waitForEvent('download')
  await panel.getByRole('button',{ name: 'Download approved handoff CSV' }).click()
  const download=await downloadEvent
  expect(download.suggestedFilename()).toMatch(/^accounting-handoff-.*\.csv$/)
  await page.getByRole('button',{ name: 'Administration',exact: true }).click()
  await page.getByLabel('Find audit event').fill('import.apply')
  await page.getByRole('button',{ name: 'Filter audit history',exact: true }).click()
  await expect(page.getByRole('list',{ name: 'Audit events' })).toContainText('import.apply')
})
