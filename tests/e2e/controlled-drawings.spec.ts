import { expect, test } from '@playwright/test'
import { authenticateSampleUser, testSupabaseUrl } from './support/auth'
import { selectContaining } from './support/select'

test('SAMPLE drawing revisions recover interrupted uploads and retain the work order’s exact approved file', async ({ page, request }) => {
  const run = `${Date.now()}-${crypto.randomUUID().slice(0, 4).toUpperCase()}`
  const client = await authenticateSampleUser(page)
  await expect(page.getByLabel('Active company')).not.toHaveValue('')
  const companyId = await page.getByLabel('Active company').inputValue()
  const item = await client.from('items').insert({ company_id: companyId, sku: `SAMPLE-DRAW-${run}`, description: 'SAMPLE drawing-controlled fastener', base_uom: 'pcs' }).select('id,sku').single()
  if (item.error) throw new Error(`SAMPLE drawing item: ${item.error.message}`)
  await page.reload()
  await page.getByRole('button', { name: 'Production', exact: true }).click()
  await page.getByRole('button', { name: 'Engineering', exact: true }).click()
  const panel = page.getByRole('region', { name: 'Controlled drawing files' })
  const number = `SAMPLE-DRAWING-${run}`
  await panel.getByText('Add drawing number', { exact: true }).click()
  await panel.getByLabel('Drawing item').selectOption(item.data.id)
  await panel.getByLabel('Drawing number', { exact: true }).fill(number)
  await panel.getByRole('button', { name: 'Create drawing number', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('Drawing number confirmed.')
  await selectContaining(page, 'Controlled drawing', number)
  await panel.getByLabel('New drawing revision').fill('A')
  await panel.getByLabel('Drawing change reason').fill('SAMPLE original controlled issue')
  await page.route('**/rest/v1/rpc/create_drawing_revision', async (route) => {
    const response = await route.fetch(); expect(response.ok()).toBe(true); await route.abort('failed')
  }, { times: 1 })
  await panel.getByRole('button', { name: 'Create drawing revision', exact: true }).click()
  await expect(panel.getByRole('alert')).toContainText('could not be confirmed')
  await expect(panel.getByLabel('New drawing revision')).toHaveValue('A')
  await panel.getByRole('button', { name: 'Create drawing revision', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('Drawing revision created.')
  await expect(panel.getByRole('button', { name: 'Approve drawing revision' })).toBeDisabled()
  const revisionA = await panel.getByLabel('Drawing revision', { exact: true }).inputValue()
  const fileA = Buffer.from('%PDF-1.7\n% SAMPLE drawing A\n%%EOF\n')
  await test.step('resume a committed upload draft after its confirmation is lost', async () => {
    await page.route('**/rest/v1/rpc/begin_drawing_document', async (route) => {
      const response = await route.fetch(); expect(response.ok()).toBe(true); await route.abort('failed')
    }, { times: 1 })
    await panel.getByLabel('Drawing file', { exact: true }).setInputFiles({ name: 'sample-a.pdf', mimeType: 'application/pdf', buffer: fileA })
    await panel.getByRole('button', { name: 'Upload drawing file', exact: true }).click()
    await expect(panel.getByRole('button', { name: 'Resume drawing upload' })).toBeVisible()
    await expect(panel.getByRole('button', { name: 'Approve drawing revision' })).toBeDisabled()
    await page.route('**/storage/v1/object/factory-evidence/**', async (route) => {
      if (route.request().method() === 'POST') {
        const response = await route.fetch(); expect(response.ok()).toBe(true); await route.abort('failed')
      } else await route.continue()
    }, { times: 1 })
    await panel.getByLabel('Drawing file', { exact: true }).setInputFiles({ name: 'sample-a.pdf', mimeType: 'application/pdf', buffer: fileA })
    await panel.getByRole('button', { name: 'Resume drawing upload' }).click()
    await expect(panel.getByRole('status')).toContainText('Drawing file upload confirmed.')
    const documents = await client.from('drawing_documents').select('id,object_path,status').eq('drawing_revision_id', revisionA)
    if (documents.error) throw new Error(documents.error.message)
    expect(documents.data).toHaveLength(1)
    expect(documents.data[0]!.status).toBe('ready')
    expect((await request.get(`${testSupabaseUrl}/storage/v1/object/public/factory-evidence/${documents.data[0]!.object_path}`)).ok()).toBe(false)
    const forbidden = await client.from('drawing_revisions').update({ status: 'approved' }).eq('id', revisionA)
    expect(forbidden.error).toBeTruthy()
  })
  async function downloadExpected(bytes: Buffer, revision: string) {
    const downloadEvent = page.waitForEvent('download')
    await page.getByRole('button', { name: `Download ${number} Rev ${revision}`, exact: true }).click()
    const download = await downloadEvent
    const stream = await download.createReadStream()
    const chunks: Buffer[] = []
    for await (const chunk of stream) chunks.push(Buffer.from(chunk))
    expect(Buffer.concat(chunks)).toEqual(bytes)
    expect(download.suggestedFilename()).toBe(`sample-${revision.toLowerCase()}.pdf`)
  }
  await downloadExpected(fileA, 'A')
  await panel.getByLabel('I reviewed this exact drawing file').check()
  await panel.getByLabel('Drawing approval reason').fill('SAMPLE reviewed stored revision A')
  await panel.getByRole('button', { name: 'Approve drawing revision', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('Drawing approval confirmed.')
  await expect(panel.getByLabel('Drawing file', { exact: true })).toHaveCount(0)
  // Existing trusted commands set up accepted demand; tested file/revision actions all run through the UI.
  const command = async (name: string, args: Record<string, unknown>) => {
    const response = await client.rpc(name, { p_company_id: companyId, p_idempotency_key: crypto.randomUUID(), ...args })
    if (response.error) throw new Error(`SAMPLE ${name}: ${response.error.message}`)
    return response.data as string
  }
  const plant = await client.from('plants').select('id').eq('company_id', companyId).limit(1).single()
  if (plant.error) throw new Error(plant.error.message)
  const centre = await client.from('work_centres').insert({ company_id: companyId, plant_id: plant.data.id, code: `SAMPLE-WC-${run}`, name: 'SAMPLE drawing workstation' }).select('id').single()
  const customer = await client.from('customers').insert({ company_id: companyId, code: `SAMPLE-C-${run}`, name: 'SAMPLE drawing customer' }).select('id').single()
  if (centre.error || customer.error) throw new Error('SAMPLE drawing prerequisites unavailable.')
  const pkg = await command('production_command', { p_action: 'create_package', p_data: { item_id: item.data.id, revision_label: `SAMPLE-${crypto.randomUUID().slice(0, 8)}`, basis_quantity: '1', components: [{ item_id: item.data.id, quantity: '1', uom: 'pcs', scrap_allowance_pct: '0' }], operations: [{ sequence: 10, work_centre_id: centre.data.id, name: 'SAMPLE operation' }] } })
  await command('production_command', { p_action: 'approve_package', p_data: { package_id: pkg } })
  const pins = await client.from('engineering_packages').select('bom_revision_id,routing_revision_id').eq('id', pkg).single()
  if (pins.error) throw new Error(pins.error.message)
  const rfq = await command('create_rfq', { p_rfq_number: `SAMPLE-RFQ-${run}`, p_customer_id: customer.data.id, p_requirement_summary: 'SAMPLE controlled drawing', p_lines: [{ item_id: item.data.id, requested_description: 'SAMPLE drawn fastener', quantity: '1', uom: 'pcs', required_by: null }] })
  await command('record_feasibility', { p_rfq_id: rfq, p_status: 'feasible', p_drawing_revision_id: revisionA, p_bom_revision_id: pins.data.bom_revision_id, p_routing_revision_id: pins.data.routing_revision_id, p_conditions: 'SAMPLE pinned A', p_expected_rfq_revision: 1 })
  const quote = await command('create_quotation', { p_rfq_id: rfq, p_quotation_number: `SAMPLE-Q-${run}`, p_currency_code: 'INR', p_valid_until: '2099-01-01', p_lines: [{ item_id: item.data.id, quantity: '1', uom: 'pcs', unit_price: '1', drawing_revision_id: revisionA, bom_revision_id: pins.data.bom_revision_id, routing_revision_id: pins.data.routing_revision_id }] })
  await command('approve_quotation', { p_quotation_id: quote, p_expected_revision: 1 })
  const order = await command('accept_quotation_create_sales_order', { p_quotation_id: quote, p_sales_order_number: `SAMPLE-SO-${run}`, p_customer_po_number: `SAMPLE-PO-${run}`, p_promised_date: '2099-01-01', p_expected_quotation_revision: 2 })
  const line = await client.from('sales_order_lines').select('id').eq('sales_order_id', order).single()
  if (line.error) throw new Error(line.error.message)
  const workNumber = `SAMPLE-WO-${run}`
  const work = await command('production_command', { p_action: 'create_work_order', p_data: { sales_order_line_id: line.data.id, package_id: pkg, number: workNumber, quantity: '1', start_date: '2031-01-01', due_date: '2031-01-02' } })
  await test.step('approve a new revision without rebinding an existing work order', async () => {
    await panel.getByLabel('New drawing revision').fill('B')
    await panel.getByLabel('Drawing change reason').fill('SAMPLE explicitly corrected drawing')
    await panel.getByRole('button', { name: 'Create drawing revision', exact: true }).click()
    await expect(panel.getByRole('status')).toContainText('Drawing revision created.')
    const fileB = Buffer.from('%PDF-1.7\n% SAMPLE drawing B\n%%EOF\n')
    await panel.getByLabel('Drawing file', { exact: true }).setInputFiles({ name: 'sample-b.pdf', mimeType: 'application/pdf', buffer: fileB })
    await panel.getByRole('button', { name: 'Upload drawing file', exact: true }).click()
    await expect(panel.getByRole('status')).toContainText('Drawing file upload confirmed.')
    await panel.getByLabel('I reviewed this exact drawing file').check()
    await panel.getByLabel('Drawing approval reason').fill('SAMPLE reviewed stored revision B')
    await panel.getByRole('button', { name: 'Approve drawing revision', exact: true }).click()
    await expect(panel.getByRole('status')).toContainText('Drawing approval confirmed.')
    await downloadExpected(fileB, 'B')
    const pinned = await client.from('work_orders').select('drawing_revision_id').eq('id', work).single()
    expect(pinned.error).toBeNull()
    expect(pinned.data?.drawing_revision_id).toBe(revisionA)
    await page.reload()
    await page.getByRole('button', { name: 'Production', exact: true }).click()
    await selectContaining(page, 'Production work order', workNumber)
    await downloadExpected(fileA, 'A')
    await expect(page.getByRole('button', { name: `Download ${number} Rev B`, exact: true })).toHaveCount(0)
  })
})
