import { createHash } from 'node:crypto'
import { expect, test } from '@playwright/test'
import { authenticateSampleUser } from './support/auth'
import { inspectAndReleaseSampleLot } from './support/quality'
import { selectContaining } from './support/select'

test('SAMPLE customer references recover retries, prevent competing mappings and retain original order/work/package pins', async ({ page }) => {
  const run = `${Date.now()}-${crypto.randomUUID().slice(0, 4).toUpperCase()}`
  let hiddenWorkspaceReads = 0
  page.on('request', (request) => { if (/\/rpc\/get_(production|quality)_workspace$/.test(new URL(request.url()).pathname)) hiddenWorkspaceReads++ })
  const client = await authenticateSampleUser(page)
  await expect(page.getByLabel('Active company')).not.toHaveValue('')
  const companyId = await page.getByLabel('Active company').inputValue()
  const plant = await client.from('plants').select('id').eq('company_id', companyId).limit(1).single()
  if (plant.error) throw new Error('SAMPLE plant unavailable.')
  const out = await client.from('items').insert({ company_id: companyId, sku: `SAMPLE-PARTOUT-${run}`, description: 'SAMPLE original factory item', base_uom: 'pcs' }).select('id,sku').single()
  const raw = await client.from('items').insert({ company_id: companyId, sku: `SAMPLE-PARTIN-${run}`, description: 'SAMPLE replacement mapping item', base_uom: 'pcs' }).select('id,sku').single()
  const customer = await client.from('customers').insert({ company_id: companyId, code: `SAMPLE-C-${run}`, name: 'SAMPLE part customer' }).select('id').single()
  const otherCustomer = await client.from('customers').insert({ company_id: companyId, code: `SAMPLE-OC-${run}`, name: 'SAMPLE other part customer' }).select('id').single()
  const wh = await client.from('warehouses').insert({ company_id: companyId, plant_id: plant.data.id, code: `SAMPLE-W-${run}`, name: 'SAMPLE part warehouse' }).select('id').single()
  const centre = await client.from('work_centres').insert({ company_id: companyId, plant_id: plant.data.id, code: `SAMPLE-WC-${run}`, name: 'SAMPLE part workstation' }).select('id').single()
  if (out.error || raw.error || customer.error || otherCustomer.error || wh.error || centre.error) throw new Error('SAMPLE reference master fixture failed.')
  const loc = await client.from('stock_locations').insert({ company_id: companyId, warehouse_id: wh.data.id, code: `SAMPLE-L-${run}`, name: 'SAMPLE part location' }).select('id').single()
  const drawing = await client.from('drawings').insert({ company_id: companyId, item_id: out.data.id, drawing_number: `SAMPLE-D-${run}` }).select('id').single()
  if (loc.error || drawing.error) throw new Error('SAMPLE drawing/location prerequisite failed.')
  const command = async (name: string, args: Record<string, unknown>) => {
    const response = await client.rpc(name, { p_company_id: companyId, p_idempotency_key: crypto.randomUUID(), ...args })
    if (response.error) throw new Error(`SAMPLE ${name}: ${response.error.message}`)
    return response.data as string
  }
  // Drawing storage already has a separate UI journey. These trusted prerequisites use real stored SAMPLE bytes.
  const revision = await command('create_drawing_revision', { p_drawing_id: drawing.data.id, p_revision: 'A', p_reason: 'SAMPLE drawing prerequisite' })
  const bytes = Buffer.from('%PDF-1.7\n% SAMPLE customer part drawing\n%%EOF\n')
  const sha = createHash('sha256').update(bytes).digest('hex')
  const document = await command('begin_drawing_document', { p_data: { drawing_revision_id: revision, original_name: 'sample-part.pdf', mime_type: 'application/pdf', byte_size: bytes.length, sha256: sha } })
  const stored = await client.storage.from('factory-evidence').upload(`${companyId}/${document}`, bytes, { contentType: 'application/pdf', upsert: false, metadata: { sha256: sha } })
  if (stored.error) throw new Error(stored.error.message)
  await command('confirm_drawing_document', { p_document_id: document })
  await command('approve_drawing_revision', { p_revision_id: revision, p_reason: 'SAMPLE checked drawing' })
  const partNumber = `SAMPLE-PN-${run}`
  const competing = { customer_id: otherCustomer.data.id, item_id: out.data.id, part_number: partNumber, part_revision: '', description: 'SAMPLE unversioned other customer', drawing_revision_id: null, reason: 'SAMPLE concurrent mapping' }
  await test.step('two concurrent mapping commands retain one active version', async () => {
    const replies = await Promise.all([1,2].map(() => client.rpc('create_customer_part_reference', { p_company_id: companyId, p_data: competing, p_idempotency_key: crypto.randomUUID() })))
    expect(replies.filter((row) => !row.error)).toHaveLength(1)
    expect(replies.find((row) => row.error)?.error?.message).toContain('CUSTOMER_PART_ACTIVE_EXISTS')
  })
  await page.reload()
  await page.getByRole('button', { name: 'Master data', exact: true }).click()
  await page.getByRole('button', { name: 'Customer part references', exact: true }).click()
  const panel = page.getByRole('region', { name: 'Customer part references' })
  async function fillMapping(itemId: string, drawingId: string | null, description: string) {
    await panel.getByLabel('Reference customer').selectOption(customer.data!.id)
    await panel.getByLabel('Reference factory item').selectOption(itemId)
    await panel.getByLabel('Customer part number', { exact: true }).fill(partNumber)
    await panel.getByLabel('Customer part revision (if supplied)').fill('A')
    await panel.getByLabel('Customer part description').fill(description)
    await panel.getByLabel('Customer part drawing').selectOption(drawingId ?? '')
    await panel.getByLabel('Reference recording reason').fill('SAMPLE checked mapping evidence')
    await panel.getByLabel('I checked the customer part, factory item and drawing reference').check()
  }
  await test.step('record a checked mapping and recover its lost server response', async () => {
    await fillMapping(out.data.id, revision, 'SAMPLE original customer part')
    await page.route('**/rest/v1/rpc/create_customer_part_reference', async (route) => {
      const response = await route.fetch(); expect(response.ok()).toBe(true)
      await expect(panel.getByLabel('Customer part number', { exact: true })).toBeDisabled()
      await route.abort('failed')
    }, { times: 1 })
    await panel.getByRole('button', { name: 'Record customer part reference', exact: true }).click()
    await expect(panel.getByRole('alert')).toContainText('could not be confirmed')
    await expect(panel.getByLabel('Customer part number', { exact: true })).toHaveValue(partNumber)
    await panel.getByRole('button', { name: 'Record customer part reference', exact: true }).click()
    await expect(panel.getByRole('status')).toContainText('Customer part reference confirmed.')
  })
  const records = await client.from('customer_item_references').select('id,reference_version').eq('company_id', companyId).eq('customer_id', customer.data.id).eq('part_number', partNumber)
  expect(records.error).toBeNull(); expect(records.data).toHaveLength(1)
  const originalId = records.data![0]!.id
  const rfqNumber = `SAMPLE-RFQ-${run}`
  const rfq = await command('create_rfq', { p_rfq_number: rfqNumber, p_customer_id: customer.data.id, p_requirement_summary: 'SAMPLE customer part order', p_lines: [{ item_id: out.data.id, requested_description: 'SAMPLE customer part', quantity: '2', uom: 'pcs', required_by: null }] })
  await command('record_feasibility', { p_rfq_id: rfq, p_status: 'feasible', p_drawing_revision_id: revision, p_bom_revision_id: null, p_routing_revision_id: null, p_conditions: 'SAMPLE drawing checked', p_expected_rfq_revision: 1 })
  await page.reload()
  await page.getByRole('button', { name: 'Sales orders', exact: true }).click()
  await page.getByRole('button', { name: 'Quotation', exact: true }).click()
  const quoteForm = page.locator('form').filter({ hasText: '2. Create quotation' })
  await quoteForm.getByLabel('Qualified RFQ').selectOption({ label: rfqNumber })
  const quoteNumber = `SAMPLE-Q-${run}`
  await quoteForm.getByLabel('Quotation number').fill(quoteNumber)
  await quoteForm.getByLabel('Item', { exact: true }).selectOption(out.data.id)
  await expect(quoteForm.getByLabel('Quotation customer part').getByRole('option')).toHaveCount(2)
  await quoteForm.getByLabel('Quotation customer part').selectOption(originalId)
  await quoteForm.getByLabel('Quantity (pcs)', { exact: true }).fill('2')
  await quoteForm.getByLabel('Unit price (INR)').fill('1')
  await quoteForm.getByLabel('Pricing source').fill('SAMPLE reviewed manual basis')
  await test.step('retain the customer reference through an interrupted quotation command', async () => {
    await page.route('**/rest/v1/rpc/create_quotation', async (route) => { const response = await route.fetch(); expect(response.ok()).toBe(true); await route.abort('failed') }, { times: 1 })
    await quoteForm.getByRole('button', { name: 'Create quotation', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('Blocked because')
    await expect(quoteForm.getByLabel('Quotation customer part')).toHaveValue(originalId)
    await quoteForm.getByRole('button', { name: 'Create quotation', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Quotation created as draft.' })).toBeVisible()
  })
  const quote = await client.from('quotations').select('id').eq('company_id', companyId).eq('quotation_number', quoteNumber).single()
  if (quote.error) throw new Error(quote.error.message)
  await page.getByRole('button', { name: 'Approval', exact: true }).click()
  await selectContaining(page, 'Draft quotation', quoteNumber)
  await expect(page.locator('.printable-quotation')).toContainText(`Customer part ${partNumber} · Rev A`)
  await page.getByRole('button', { name: 'Approve quotation', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Quotation approved.' })).toBeVisible()
  await page.getByRole('button', { name: 'Master data', exact: true }).click()
  await page.getByRole('button', { name: 'Customer part references', exact: true }).click()
  await panel.getByLabel('Find customer part').fill(partNumber)
  await panel.getByRole('button', { name: `Retire ${partNumber} Rev A mapping v1`, exact: true }).click()
  await panel.getByLabel('Reference retirement reason').fill('SAMPLE correction to a different factory item')
  await panel.getByRole('button', { name: 'Retire customer part reference', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('Customer part reference retired.')
  await fillMapping(raw.data.id, null, 'SAMPLE corrected customer mapping')
  await panel.getByRole('button', { name: 'Record customer part reference', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('Customer part reference confirmed.')
  await expect(panel.getByRole('list', { name: 'Customer part reference records' })).toContainText(`${raw.data.sku} · SAMPLE corrected customer mapping · Mapping v2`)
  await panel.getByLabel('Include retired references').check()
  await expect(panel.getByRole('list', { name: 'Customer part reference records' })).toContainText(`${out.data.sku} · SAMPLE original customer part · Mapping v1`)
  await page.getByRole('button', { name: 'Sales orders', exact: true }).click()
  await page.getByRole('button', { name: 'Order acceptance', exact: true }).click()
  await selectContaining(page, 'Approved quotation', quoteNumber)
  const orderNumber = `SAMPLE-SO-${run}`
  await page.getByLabel('Sales order number').fill(orderNumber)
  await page.getByLabel('Customer PO number').fill(`SAMPLE-PO-${run}`)
  await page.getByRole('button', { name: 'Create sales order', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Sales order created.' })).toBeVisible()
  expect(hiddenWorkspaceReads).toBe(0)
  const order = await client.from('sales_orders').select('id').eq('company_id', companyId).eq('sales_order_number', orderNumber).single()
  if (order.error) throw new Error(order.error.message)
  const line = await client.from('sales_order_lines').select('id,customer_part_reference_id,item_id').eq('sales_order_id', order.data.id).single()
  expect(line.error).toBeNull(); expect(line.data?.customer_part_reference_id).toBe(originalId); expect(line.data?.item_id).toBe(out.data.id)
  const pkg = await command('production_command', { p_action: 'create_package', p_data: { item_id: out.data.id, revision_label: `SAMPLE-${crypto.randomUUID().slice(0, 8)}`, basis_quantity: '1', components: [{ item_id: raw.data.id, quantity: '1', uom: 'pcs', scrap_allowance_pct: '0' }], operations: [{ sequence: 10, work_centre_id: centre.data.id, name: 'SAMPLE operation' }] } })
  await command('production_command', { p_action: 'approve_package', p_data: { package_id: pkg } })
  const workNumber = `SAMPLE-WO-${run}`
  await command('production_command', { p_action: 'create_work_order', p_data: { sales_order_line_id: line.data!.id, package_id: pkg, number: workNumber, quantity: '1', start_date: '2031-01-01', due_date: '2031-01-02' } })
  const lotCode = `SAMPLE-PARTLOT-${run}`
  const lot = await command('receive_finished_goods', { p_item_id: out.data.id, p_location_id: loc.data.id, p_lot_code: lotCode, p_quantity: '1', p_uom: 'pcs' })
  await page.reload()
  await page.getByRole('button', { name: 'Production', exact: true }).click()
  await selectContaining(page, 'Production work order', workNumber)
  await expect(page.getByRole('region', { name: 'Production planning and execution' })).toContainText(`Customer part ${partNumber} · Rev A`)
  await inspectAndReleaseSampleLot(page, { sku: out.data.sku, lot: lotCode, planLabel: `SAMPLE-PLAN-${run}` })
  const reservation = await command('reserve_finished_goods', { p_sales_order_line_id: line.data!.id, p_lot_id: lot, p_quantity: '1', p_expected_sales_order_revision: 1 })
  await page.reload()
  await test.step('print actual packages with the original agreed customer part and factory item', async () => {
    await page.getByRole('button', { name: 'Dispatch', exact: true }).click()
    await selectContaining(page, 'Sales order', orderNumber)
    await page.getByLabel('Active reservation').selectOption(reservation)
    const shipmentNumber = `SAMPLE-SHIP-${run}`
    await page.getByLabel('Packing number').fill(`SAMPLE-PACK-${run}`)
    await page.getByLabel('Shipment number').fill(shipmentNumber)
    await page.getByLabel('Packed quantity').fill('1')
    await page.getByRole('button', { name: 'Prepare shipment', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Packed shipment prepared' })).toBeVisible()
    await selectContaining(page, 'Package shipment line', shipmentNumber)
    await page.getByLabel('Package code', { exact: true }).fill(`SAMPLE-BOX-${run}`)
    await page.getByLabel('Package quantity', { exact: true }).fill('1')
    await page.getByRole('button', { name: 'Record package contents', exact: true }).click()
    const labels = page.locator('.package-print-sheet')
    await expect(labels).toContainText(`Customer part ${partNumber} · Rev A`)
    await expect(labels).toContainText(`Item ${out.data.sku}`)
    await expect(labels).not.toContainText(raw.data.sku)
    await page.emulateMedia({ media: 'print' })
    await expect(labels).toBeVisible()
    await expect(labels.locator('.package-label')).toHaveCount(1)
  })
})
