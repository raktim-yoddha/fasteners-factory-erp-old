import { expect, test } from '@playwright/test'
import { authenticateSampleUser } from './support/auth'
import { inspectAndReleaseSampleLot } from './support/quality'
import { selectContaining } from './support/select'

test('SAMPLE partial dispatch and customer returns contain goods, bound concurrent receipts and recover a lost confirmation', async ({ page }) => {
  const run = `${Date.now()}-${crypto.randomUUID().slice(0, 4).toUpperCase()}`
  const client = await authenticateSampleUser(page)
  await expect(page.getByLabel('Active company')).not.toHaveValue('')
  const companyId = await page.getByLabel('Active company').inputValue()
  const plant = await client.from('plants').select('id').eq('company_id', companyId).limit(1).single()
  if (plant.error) throw new Error(`SAMPLE plant: ${plant.error.code}`)
  const item = await client.from('items').insert({ company_id: companyId, sku: `SAMPLE-RET-${run}`, description: 'SAMPLE returned fasteners', base_uom: 'pcs' }).select('id,sku').single()
  const customer = await client.from('customers').insert({ company_id: companyId, code: `SAMPLE-C-${run}`, name: 'SAMPLE return customer' }).select('id').single()
  const wh = await client.from('warehouses').insert({ company_id: companyId, plant_id: plant.data.id, code: `SAMPLE-W-${run}`, name: 'SAMPLE return warehouse' }).select('id').single()
  if (item.error || customer.error || wh.error) throw new Error('SAMPLE return master fixture failed')
  const loc = await client.from('stock_locations').insert({ company_id: companyId, warehouse_id: wh.data.id, code: `SAMPLE-L-${run}`, name: 'SAMPLE return receiving' }).select('id').single()
  if (loc.error) throw new Error(`SAMPLE receiving: ${loc.error.message}`)
  const command = async (name: string, data: Record<string, unknown>) => {
    const result = await client.rpc(name, { p_company_id: companyId, ...data, p_idempotency_key: crypto.randomUUID() })
    if (result.error) throw new Error(`SAMPLE ${name}: ${result.error.message}`)
    return result.data as string
  }
  const rfq = await command('create_rfq', { p_rfq_number: `SAMPLE-RFQ-${run}`, p_customer_id: customer.data.id, p_requirement_summary: 'SAMPLE return fixture', p_lines: [{ item_id: item.data.id, requested_description: 'SAMPLE fasteners', quantity: '10', uom: 'pcs', required_by: null }] })
  await command('record_feasibility', { p_rfq_id: rfq, p_status: 'feasible', p_drawing_revision_id: null, p_bom_revision_id: null, p_routing_revision_id: null, p_conditions: 'SAMPLE stock supply', p_expected_rfq_revision: 1 })
  const quote = await command('create_quotation', { p_rfq_id: rfq, p_quotation_number: `SAMPLE-Q-${run}`, p_currency_code: 'INR', p_valid_until: '2099-01-01', p_lines: [{ item_id: item.data.id, quantity: '10', uom: 'pcs', unit_price: '1' }] })
  await command('approve_quotation', { p_quotation_id: quote, p_expected_revision: 1 })
  const soNumber = `SAMPLE-SO-${run}`
  const so = await command('accept_quotation_create_sales_order', { p_quotation_id: quote, p_sales_order_number: soNumber, p_customer_po_number: `SAMPLE-PO-${run}`, p_promised_date: '2099-01-01', p_expected_quotation_revision: 2 })
  const line = await client.from('sales_order_lines').select('id').eq('sales_order_id', so).single()
  if (line.error) throw new Error(`SAMPLE demand: ${line.error.message}`)
  const sourceCode = `SAMPLE-SOURCE-${run}`
  const source = await command('receive_finished_goods', { p_item_id: item.data.id, p_location_id: loc.data.id, p_lot_code: sourceCode, p_quantity: '10', p_uom: 'pcs' })
  await page.reload()
  const planId = await inspectAndReleaseSampleLot(page, { sku: item.data.sku, lot: sourceCode, planLabel: `SAMPLE-PLAN-${run}` })
  const reservation = await command('reserve_finished_goods', { p_sales_order_line_id: line.data.id, p_lot_id: source, p_quantity: '10', p_expected_sales_order_revision: 1 })
  await page.reload()
  const shipNumber = `SAMPLE-SHIP-${run}`
  await test.step('partially pack and gate out actual reserved quantity', async () => {
    await page.getByRole('button', { name: 'Dispatch', exact: true }).click()
    await selectContaining(page, 'Sales order', soNumber)
    await page.getByLabel('Active reservation').selectOption(reservation)
    await page.getByLabel('Packing number').fill(`SAMPLE-PACK-${run}`)
    await page.getByLabel('Shipment number').fill(shipNumber)
    await page.getByLabel('Packed quantity').fill('6')
    await page.route('**/rest/v1/rpc/prepare_packing_shipment', async (route) => {
      const response = await route.fetch()
      expect(response.ok()).toBeTruthy()
      await route.abort('failed')
    }, { times: 1 })
    await page.getByRole('button', { name: 'Prepare shipment', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('server rejected this dispatch action')
    await expect(page.getByLabel('Packed quantity')).toHaveValue('6')
    await page.getByRole('button', { name: 'Prepare shipment', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Packed shipment prepared' })).toBeVisible()
    await selectContaining(page, 'Prepared shipment', shipNumber)
    await selectContaining(page, 'Package shipment line', shipNumber)
    await page.getByLabel('Package code', { exact: true }).fill(`SAMPLE-BOX1-${run}`)
    await page.getByLabel('Package quantity', { exact: true }).fill('2')
    await page.getByRole('button', { name: 'Record package contents', exact: true }).click()
    await expect(page.getByLabel('Package quantity balance')).toContainText('In packages 2.000000 pcs')
    await page.getByRole('button', { name: 'Dispatch shipment', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('package quantities do not cover every shipment line')
    await page.getByLabel('Package code', { exact: true }).fill(`SAMPLE-BOX2-${run}`)
    await page.getByLabel('Package quantity', { exact: true }).fill('4')
    await page.getByRole('button', { name: 'Record package contents', exact: true }).click()
    await expect(page.getByLabel('Package quantity balance')).toContainText('Unlabelled 0.000000 pcs')
    await page.emulateMedia({ media: 'print' })
    await expect(page.locator('main')).toBeHidden()
    await expect(page.locator('.package-print-sheet')).toBeVisible()
    await expect(page.locator('.package-print-sheet .package-label')).toHaveCount(2)
    await expect(page.locator('.package-print-sheet')).toContainText(`Lot ${sourceCode}`)
    await expect(page.locator('.package-print-sheet')).toContainText('Quantity 4.000000 pcs')
    await page.emulateMedia({ media: 'screen' })
    await page.getByRole('button', { name: 'Dispatch shipment', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Shipment dispatched' })).toBeVisible()
  })
  await page.getByRole('button', { name: 'Customer returns', exact: true }).click()
  await selectContaining(page, 'Dispatched shipment line', shipNumber)
  const returnLot = `SAMPLE-RETLOT-${run}`
  const fillReturn = async (suffix: string, quantity: string) => {
    await page.getByLabel('Customer return number').fill(`SAMPLE-RET${suffix}-${run}`)
    await page.getByLabel('Returned stock lot code').fill(suffix === 'ONE' ? returnLot : `SAMPLE-RETLOT${suffix}-${run}`)
    await page.getByLabel('Customer return quantity', { exact: true }).fill(quantity)
    await page.getByLabel('Return receiving location').selectOption(loc.data.id)
    await page.getByLabel('Customer return reference').fill('SAMPLE physical inward note')
    await page.getByLabel('Customer return reason').fill('SAMPLE customer complaint')
  }
  await test.step('recover the same receipt after the server confirmation is lost', async () => {
    await fillReturn('ONE', '2')
    await page.route('**/rest/v1/rpc/receive_customer_return', async (route) => {
      const response = await route.fetch()
      expect(response.ok()).toBeTruthy()
      await route.abort('failed')
    }, { times: 1 })
    await page.getByRole('button', { name: 'Receive customer return', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('return could not be confirmed')
    await expect(page.getByLabel('Customer return quantity', { exact: true })).toHaveValue('2')
    await page.getByRole('button', { name: 'Receive customer return', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Customer return received' })).toBeVisible()
    await expect(page.getByLabel('Customer return balance')).toContainText('Already returned 2.000000 pcs')
  })
  await test.step('concurrent different receipts cannot both exceed the shipped remainder', async () => {
    const workspace = await client.rpc('get_customer_return_workspace', { p_company_id: companyId })
    const shipment = workspace.data.shipments.find((row: { shipment_number: string }) => row.shipment_number === shipNumber)
    const input = { shipment_line_id: shipment.id, shipment_revision: shipment.shipment_revision, location_id: loc.data.id, quantity: '3', uom: 'pcs', reference: 'SAMPLE concurrent receipt', reason: 'SAMPLE counted physical return' }
    const results = await Promise.all(['A', 'B'].map((suffix) => client.rpc('receive_customer_return', { p_company_id: companyId, p_data: { ...input, return_number: `SAMPLE-RETC${suffix}-${run}`, lot_code: `SAMPLE-RETCLOT${suffix}-${run}` }, p_idempotency_key: crypto.randomUUID() })))
    expect(results.filter((result) => !result.error)).toHaveLength(1)
    expect(results.find((result) => result.error)?.error?.message).toContain('CUSTOMER_RETURN_QUANTITY_EXCEEDED')
    await page.reload()
    await page.getByRole('button', { name: 'Dispatch', exact: true }).click()
    await page.getByRole('button', { name: 'Customer returns', exact: true }).click()
    await selectContaining(page, 'Dispatched shipment line', shipNumber)
    await expect(page.getByLabel('Customer return balance')).toContainText('Returnable 1.000000 pcs')
    await fillReturn('LAST', '1')
    await page.getByRole('button', { name: 'Receive customer return', exact: true }).click()
    await expect(page.getByLabel('Customer return balance')).toContainText('Returnable 0.000000 pcs')
    await expect(page.getByRole('button', { name: 'Receive customer return', exact: true })).toBeDisabled()
  })
  await test.step('retain shipment genealogy and require fresh final QC', async () => {
    await page.getByRole('button', { name: 'Quality', exact: true }).click()
    await page.getByRole('button', { name: 'Traceability', exact: true }).click()
    await selectContaining(page, 'Trace lot', returnLot)
    await expect(page.getByText(`Original shipment: ${shipNumber}`, { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: `Source ${sourceCode}`, exact: true })).toBeVisible()
    await inspectAndReleaseSampleLot(page, { sku: item.data.sku, lot: returnLot, planLabel: `SAMPLE-PLAN-${run}`, planId, context: 'final' })
    const balance = await client.from('stock_positions').select('on_hand::text,reserved::text').eq('lot_id', source).single()
    expect(balance.data).toMatchObject({ on_hand: '4.000000', reserved: '4.000000' })
    const demand = await client.from('sales_orders').select('status,revision').eq('id', so).single()
    expect(demand.data).toMatchObject({ status: 'partially_shipped', revision: 3 })
    const receipts = await client.from('customer_return_receipts').select('id').eq('shipment_line_id', (await client.rpc('get_customer_return_workspace', { p_company_id: companyId })).data.shipments.find((row: { shipment_number: string }) => row.shipment_number === shipNumber).id)
    expect(receipts.data).toHaveLength(3)
  })
})
