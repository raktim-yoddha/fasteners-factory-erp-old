import { expect, test } from '@playwright/test'
import { authenticateSampleUser } from './support/auth'
import { plantDate } from '../../src/lib/decimal'

test('SAMPLE reports filter exact stock events by plant date, validate ranges and drill into records', async ({ page }) => {
  const client = await authenticateSampleUser(page)
  await expect(page.getByLabel('Active company')).not.toHaveValue('')
  const companyId = await page.getByLabel('Active company').inputValue()
  const run = `${Date.now()}-${crypto.randomUUID().slice(0, 4).toUpperCase()}`
  const item = await client.from('items').insert({ company_id: companyId, sku: `SAMPLE-REPORT-${run}`, description: 'SAMPLE movement report fixture', base_uom: 'kg' }).select('id,sku').single()
  const location = await client.from('stock_locations').select('id').eq('company_id', companyId).eq('active', true).limit(1).single()
  if (item.error || location.error) throw new Error('SAMPLE report prerequisites unavailable')
  const lotCode = `SAMPLE-REPORTLOT-${run}`
  const receive = await client.rpc('receive_finished_goods', { p_company_id: companyId, p_item_id: item.data.id, p_location_id: location.data.id, p_lot_code: lotCode, p_quantity: '0.000001', p_uom: 'kg', p_idempotency_key: crypto.randomUUID() })
  if (receive.error) throw new Error(`SAMPLE report receipt: ${receive.error.message}`)
  await page.getByRole('button', { name: 'Reports', exact: true }).click()
  await page.getByLabel('Factory report', { exact: true }).selectOption('movements')
  await page.getByLabel('Find record, item or party').fill(item.data.sku)
  await page.getByLabel('Created / posted from').fill(plantDate())
  await page.getByLabel('Created / posted to').fill(plantDate())
  await page.getByRole('button', { name: 'Apply report filters' }).click()
  await expect(page.getByText('Signed movement: 0.000001 kg', { exact: true })).toBeVisible()
  await expect(page.getByRole('status').filter({ hasText: '1 matching records' })).toBeVisible()
  await page.getByLabel('Created / posted from').fill('2099-01-02')
  await page.getByLabel('Created / posted to').fill('2099-01-01')
  await page.getByRole('button', { name: 'Apply report filters' }).click()
  await expect(page.getByRole('alert')).toContainText('From date must be on or before To date')
  await page.getByLabel('Created / posted from').fill('2000-01-01')
  await page.getByLabel('Created / posted to').fill('2000-01-01')
  await page.getByRole('button', { name: 'Apply report filters' }).click()
  await expect(page.getByText('No matching records.', { exact: false })).toBeVisible()
  await page.getByLabel('Created / posted from').fill('')
  await page.getByLabel('Created / posted to').fill('')
  await page.getByRole('button', { name: 'Apply report filters' }).click()
  await expect(page.getByText('Signed movement: 0.000001 kg', { exact: true })).toBeVisible()
  const added = await client.rpc('receive_finished_goods', { p_company_id: companyId, p_item_id: item.data.id, p_location_id: location.data.id, p_lot_code: lotCode, p_quantity: '0.123456', p_uom: 'kg', p_idempotency_key: crypto.randomUUID() })
  if (added.error) throw new Error(`SAMPLE report additional event: ${added.error.message}`)
  await page.getByRole('button', { name: 'Refresh report' }).click()
  await expect(page.getByRole('status').filter({ hasText: '2 matching records' })).toBeVisible()
  await expect(page.getByText('Signed movement: 0.123456 kg', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: `Open ${lotCode}`, exact: true }).first().click()
  await expect(page).toHaveURL(new RegExp(`/records/lot/${receive.data}$`))
  await expect(page.getByRole('heading', { name: lotCode, exact: true })).toBeVisible()
})
