import { expect, test } from '@playwright/test'
import { authenticateSampleUser } from './support/auth'
import { selectContaining } from './support/select'

test('SAMPLE controlled specifications and converted receipts recover interrupted confirmations', async ({ page }) => {
  const client = await authenticateSampleUser(page)
  await expect(page.getByLabel('Active company')).not.toHaveValue('')
  const companyId = await page.getByLabel('Active company').inputValue(), run = crypto.randomUUID().slice(0,8).toUpperCase()
  const item = await client.from('items').insert({ company_id: companyId, sku: `SAMPLE-SPEC-${run}`, description: 'SAMPLE controlled bolt', base_uom: 'pcs' }).select('id,sku').single()
  const supplier = await client.from('suppliers').insert({ company_id: companyId, code: `SAMPLE-SP-${run}`, name: 'SAMPLE units supplier' }).select('id').single()
  const loc = await client.from('stock_locations').select('id').eq('company_id',companyId).limit(1).single()
  if (item.error || supplier.error || loc.error) throw new Error('SAMPLE units fixture failed')
  await page.reload()
  await page.getByRole('button',{ name: 'Master data', exact: true }).click()
  await page.getByRole('button',{ name: 'Specifications and units', exact: true }).click()
  const panel = page.getByRole('region',{ name: 'Specifications and units' })
  await selectContaining(page,'Controlled item',item.data.sku)
  await panel.getByLabel('Product type').fill('SAMPLE bolt')
  await panel.getByLabel('Nominal diameter (mm)').fill('8.000001')
  await panel.getByLabel('Specification evidence').fill('SAMPLE drawing measurement record')
  await page.route('**/rest/v1/rpc/item_control_command',async (route) => { const response = await route.fetch(); expect(response.ok()).toBe(true); await route.abort('failed') },{ times: 1 })
  await panel.getByRole('button',{ name: 'Record specification draft', exact: true }).click()
  await expect(panel.getByRole('alert')).toContainText('could not be confirmed')
  await expect(panel.getByLabel('Nominal diameter (mm)')).toHaveValue('8.000001')
  await panel.getByRole('button',{ name: 'Record specification draft', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('Item control confirmed.')
  await panel.getByLabel('Specification approval reason').fill('SAMPLE checked drawing against SKU')
  await panel.getByRole('button',{ name: 'Approve specification v1', exact: true }).click()
  await expect(panel.getByRole('list',{ name: 'Specification history' })).toContainText('✓ approved')
  const specs = await client.from('item_specification_versions').select('id').eq('item_id',item.data.id)
  expect(specs.error).toBeNull(); expect(specs.data).toHaveLength(1)
  await panel.getByRole('button',{ name: 'Unit conversions', exact: true }).click()
  await panel.getByLabel('Alternate unit').selectOption('box')
  await panel.getByLabel('Measured alternate quantity').fill('1')
  await panel.getByLabel('Equivalent quantity (pcs)').fill('10')
  await panel.getByLabel('Conversion measurement / packing evidence').fill('SAMPLE counted sealed box of ten pieces')
  await panel.getByRole('button',{ name: 'Record conversion draft', exact: true }).click()
  await expect(panel.getByRole('button',{ name: 'Approve box conversion v1', exact: true })).toBeVisible()
  await panel.getByLabel('Conversion approval reason').fill('SAMPLE basis verified')
  await panel.getByRole('button',{ name: 'Approve box conversion v1', exact: true }).click()
  await expect(panel.getByRole('list',{ name: 'Unit conversion history' })).toContainText('✓ approved')
  const basis = await client.from('item_unit_conversions').select('id').eq('item_id',item.data.id).single()
  if (basis.error) throw new Error(basis.error.message)
  const command = async (name: string, args: Record<string,unknown>) => {
    const result = await client.rpc(name,{ p_company_id: companyId,p_idempotency_key: crypto.randomUUID(),...args })
    if (result.error) throw new Error(result.error.message)
    return result.data as string
  }
  const req = await command('request_material',{ p_number: `SAMPLE-REQ-${run}`,p_item_id: item.data.id,p_quantity: '20',p_uom: 'pcs',p_demand_source: 'SAMPLE replenishment',p_needed_by: '2031-01-01',p_sales_order_line_id: null })
  const poNumber = `SAMPLE-PO-${run}`
  const po = await command('create_purchase_order',{ p_requisition_id: req,p_supplier_id: supplier.data.id,p_number: poNumber,p_unit_price: '1',p_currency: 'INR',p_promised_date: '2031-01-01',p_expected_revision: 1 })
  await command('approve_purchase_order',{ p_order_id: po,p_expected_revision: 1 })
  await page.reload()
  await page.getByRole('button',{ name: 'Purchasing', exact: true }).click()
  await page.getByRole('button',{ name: 'Receive delivery', exact: true }).click()
  const purchase = page.getByRole('region',{ name: 'Material purchasing' })
  await selectContaining(page,'Purchase order',poNumber)
  await purchase.getByLabel('Receipt number').fill(`SAMPLE-GRN-${run}`)
  await purchase.getByLabel('Internal lot code').fill(`SAMPLE-LOT-${run}`)
  await purchase.getByLabel('Supplier lot / heat reference').fill(`SAMPLE-HEAT-${run}`)
  await purchase.getByLabel('Receiving location').selectOption(loc.data.id)
  await purchase.getByLabel('Receipt quantity unit').selectOption(basis.data.id)
  await purchase.getByLabel('Received quantity (box)').fill('0.15')
  await purchase.getByRole('button',{ name: 'Confirm goods receipt', exact: true }).click()
  await expect(purchase.getByRole('alert')).toContainText('rounding')
  await purchase.getByLabel('Received quantity (box)').fill('2')
  await page.route('**/rest/v1/rpc/receive_purchase_order_in_unit',async (route) => { const response = await route.fetch(); expect(response.ok()).toBe(true); await route.abort('failed') },{ times: 1 })
  await purchase.getByRole('button',{ name: 'Confirm goods receipt', exact: true }).click()
  await expect(purchase.getByRole('alert')).toContainText('could not be confirmed')
  await purchase.getByRole('button',{ name: 'Confirm goods receipt', exact: true }).click()
  await expect(purchase.getByRole('status').filter({ hasText: 'Delivery received in QC hold.' })).toBeVisible()
  await expect(purchase).toContainText('Recorded 2.000000 box using approved conversion')
  const events = await client.from('unit_conversion_events').select('base_quantity,input_quantity').eq('company_id',companyId).eq('item_id',item.data.id)
  expect(events.error).toBeNull(); expect(events.data).toHaveLength(1); expect(String(events.data![0]!.base_quantity)).toBe('20')
})
