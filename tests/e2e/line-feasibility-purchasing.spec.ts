import { expect, test } from '@playwright/test'
import { authenticateSampleUser } from './support/auth'
import { selectContaining } from './support/select'

test('SAMPLE mixed-item enquiries use line reviews and purchasing allocates only remaining demand', async ({ page }) => {
  const client = await authenticateSampleUser(page)
  await expect(page.getByLabel('Active company')).not.toHaveValue('')
  const companyId = await page.getByLabel('Active company').inputValue(), run = crypto.randomUUID().slice(0,8).toUpperCase()
  const items = await client.from('items').insert([{ company_id: companyId, sku: `SAMPLE-A-${run}`, description: 'SAMPLE bolt',base_uom: 'pcs' },{ company_id: companyId, sku: `SAMPLE-B-${run}`,description: 'SAMPLE nut',base_uom: 'pcs' }]).select('id,sku')
  const customer = await client.from('customers').insert({ company_id: companyId,code: `SAMPLE-C-${run}`,name: 'SAMPLE line customer' }).select('id').single()
  const suppliers = await client.from('suppliers').insert([1,2].map((n) => ({ company_id: companyId,code: `SAMPLE-S${n}-${run}`,name: `SAMPLE supplier ${n}` }))).select('id')
  if (items.error || customer.error || suppliers.error || items.data.length!==2 || suppliers.data.length!==2) throw new Error('SAMPLE line fixtures unavailable')
  const a = items.data[0]!, b = items.data[1]!
  const command = async (name: string,args: Record<string,unknown>) => {
    const result = await client.rpc(name,{ p_company_id: companyId,p_idempotency_key: crypto.randomUUID(),...args })
    if (result.error) throw new Error(result.error.message)
    return result.data as string
  }
  const rfqNumber = `SAMPLE-RFQ-${run}`
  const rfq = await command('create_rfq',{ p_rfq_number: rfqNumber,p_customer_id: customer.data.id,p_requirement_summary: 'SAMPLE separate line review',p_lines: [a,b].map((item) => ({ item_id: item.id,requested_description: item.sku,quantity: '10',uom: 'pcs' })) })
  const lines = await client.from('rfq_lines').select('id,item_id').eq('rfq_id',rfq)
  if (lines.error) throw new Error(lines.error.message)
  await page.reload()
  await page.getByRole('button',{ name: 'Sales orders',exact: true }).click()
  await page.getByLabel('RFQ',{ exact: true }).selectOption(rfq)
  await expect(page.getByLabel('Feasibility scope').getByRole('option')).toHaveCount(3)
  await page.getByLabel('Feasibility scope').selectOption(lines.data.find((line) => line.item_id===a.id)!.id)
  await page.getByLabel('Conditions or reason').fill('SAMPLE drawing checked')
  await page.getByRole('button',{ name: 'Record feasibility',exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Feasibility review recorded.' })).toBeVisible()
  await page.getByLabel('Feasibility scope').selectOption(lines.data.find((line) => line.item_id===b.id)!.id)
  await page.getByLabel('Result',{ exact: true }).selectOption('not_feasible')
  await page.getByLabel('Conditions or reason').fill('SAMPLE unsupported process')
  await page.getByRole('button',{ name: 'Record feasibility',exact: true }).click()
  await expect.poll(async () => (await client.from('rfqs').select('revision').eq('id',rfq).single()).data?.revision).toBe(3)
  await page.getByRole('button',{ name: 'Quotation',exact: true }).click()
  await page.getByLabel('Qualified RFQ').selectOption(rfq)
  const enquiryLine = page.getByLabel('Qualified enquiry line')
  await expect(enquiryLine.getByRole('option')).toHaveCount(2)
  await enquiryLine.selectOption(lines.data.find((line) => line.item_id===a.id)!.id)
  await expect(page.getByLabel('Item',{ exact: true })).toHaveValue(a.id)
  await page.getByLabel('Quotation number').fill(`SAMPLE-Q-${run}`)
  await page.getByLabel('Quantity (pcs)',{ exact: true }).fill('10')
  await page.getByLabel('Unit price (INR)').fill('1')
  await page.getByLabel('Pricing source').fill('SAMPLE approved costing record')
  await page.getByRole('button',{ name: 'Create quotation',exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Quotation created as draft.' })).toBeVisible()
  const req = await command('request_material',{ p_number: `SAMPLE-REQ-${run}`,p_item_id: a.id,p_quantity: '10',p_uom: 'pcs',p_demand_source: 'SAMPLE supplier split',p_needed_by: '2031-01-01',p_sales_order_line_id: null })
  const replies = await Promise.all(suppliers.data.map((supplier,index) => client.rpc('create_partial_purchase_order',{ p_company_id: companyId,p_requisition_id: req,p_supplier_id: supplier.id,p_number: `SAMPLE-CONCURRENT-${index}-${run}`,p_quantity: '4',p_unit_price: '1',p_currency: 'INR',p_promised_date: '2031-01-01',p_expected_revision: 1,p_idempotency_key: crypto.randomUUID() })))
  expect(replies.filter((row) => !row.error)).toHaveLength(1)
  expect(replies.find((row) => row.error)?.error?.message).toContain('REVISION_CONFLICT')
  await page.reload()
  await page.getByRole('button',{ name: 'Purchasing',exact: true }).click()
  await page.getByRole('button',{ name: 'Draft PO',exact: true }).click()
  await selectContaining(page,'Requested material',`SAMPLE-REQ-${run}`)
  await expect(page.getByRole('region',{ name: 'Material purchasing' })).toContainText('Remaining 6.000000 pcs')
  await page.getByLabel('Purchase supplier').selectOption(suppliers.data[1]!.id)
  await page.getByLabel('Purchase order number').fill(`SAMPLE-REMAINING-${run}`)
  await page.getByLabel('PO quantity (pcs)').fill('6')
  await page.getByLabel('Purchase unit price').fill('1')
  await page.getByRole('button',{ name: 'Create draft PO',exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Purchase order drafted.' })).toBeVisible()
  const allocation = await client.from('purchase_requisition_positions').select('allocated_quantity,remaining_quantity').eq('requisition_id',req).single()
  expect(allocation.error).toBeNull(); expect(String(allocation.data?.allocated_quantity)).toBe('10'); expect(String(allocation.data?.remaining_quantity)).toBe('0')
})
