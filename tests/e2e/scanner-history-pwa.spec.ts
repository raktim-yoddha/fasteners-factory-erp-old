import { expect,test } from '@playwright/test'
import { authenticateSampleUser } from './support/auth'

test('SAMPLE scanner lookup requires an exact match and stock history reaches events beyond 100', async ({ page }) => {
  const client=await authenticateSampleUser(page)
  await expect(page.getByLabel('Active company')).not.toHaveValue('')
  const companyId=await page.getByLabel('Active company').inputValue(),run=crypto.randomUUID().slice(0,8).toUpperCase(),code=`SAMPLE-SCAN-${run}`
  const item=await client.from('items').insert({ company_id: companyId,sku: `SAMPLE-SCAN-I-${run}`,description: 'SAMPLE scanner history item',base_uom: 'pcs' }).select('id').single()
  const loc=await client.from('stock_locations').select('id').eq('company_id',companyId).limit(1).single()
  if (item.error || loc.error) throw new Error('SAMPLE scanner masters failed')
  const receipt={ p_company_id: companyId,p_item_id: item.data.id,p_location_id: loc.data.id,p_lot_code: code,p_quantity: '1',p_uom: 'pcs' }
  const first=await client.rpc('receive_finished_goods',{ ...receipt,p_idempotency_key: crypto.randomUUID() })
  if (first.error) throw first.error
  const receipts=await Promise.all(Array.from({ length: 102 },() => client.rpc('receive_finished_goods',{ ...receipt,p_idempotency_key: crypto.randomUUID() })))
  expect(receipts.every((result) => !result.error)).toBe(true)
  const relatedLots=await Promise.all(Array.from({ length: 24 },(_,n) => client.rpc('receive_finished_goods',{ ...receipt,p_lot_code: `${code}-${n+1}`,p_idempotency_key: crypto.randomUUID() })))
  expect(relatedLots.every((result) => !result.error)).toBe(true)
  const events=await client.from('stock_ledger_entries').select('id::text').eq('company_id',companyId).eq('lot_id',first.data).order('id',{ ascending: false })
  if (events.error) throw events.error
  expect(events.data).toHaveLength(103)
  await page.reload()
  await page.getByText('Scan an identifier',{ exact: true }).click()
  await page.getByLabel('Scanned identifier').fill(code.slice(0,-1))
  await page.getByLabel('Scanned identifier').press('Enter')
  await expect(page.getByText('No permitted exact match. Check the code and active company.')).toBeVisible()
  await page.getByLabel('Scanned identifier').fill(code)
  await page.getByLabel('Scanned identifier').press('Enter')
  const scanned=page.getByRole('list',{ name: 'Scanned records' })
  await expect(scanned).toContainText(`${code} · hold`)
  await scanned.getByRole('button').click()
  await expect(page).toHaveURL(new RegExp(`/records/lot/${first.data}$`))
  await expect(page.getByRole('heading',{ name: code,exact: true })).toBeVisible()
  const audit=await client.from('audit_log').select('id::text').eq('company_id',companyId).eq('entity_id',first.data).order('id',{ ascending: false })
  if (audit.error) throw audit.error
  expect(audit.data).toHaveLength(103)
  await page.getByRole('tab',{ name: 'Timeline',exact: true }).click()
  const timelinePages=page.getByRole('navigation',{ name: 'Record timeline pages' })
  await expect(page.getByRole('tabpanel')).toContainText(`Event ${audit.data[0]!.id} ·`)
  for (let offset=20;offset<103;offset+=20) {
    await timelinePages.getByRole('button',{ name: 'Older events' }).click()
    await expect(page.getByRole('tabpanel')).toContainText(`Event ${audit.data[offset]!.id} ·`)
  }
  await expect(timelinePages.getByRole('button',{ name: 'Older events' })).toBeDisabled()
  await expect(page.getByRole('tabpanel')).toContainText(`Event ${audit.data[102]!.id} ·`)
  await page.getByRole('tab',{ name: 'Linked records',exact: true }).click()
  await page.getByRole('list',{ name: 'Related records' }).getByRole('button',{ name: 'Open',exact: true }).click()
  await page.getByRole('tab',{ name: 'Linked records',exact: true }).click()
  const related=page.getByRole('list',{ name: 'Related records' })
  await expect(related.getByRole('listitem')).toHaveCount(20)
  const linkPages=page.getByRole('navigation',{ name: 'Linked record pages' })
  await linkPages.getByRole('button',{ name: 'More links' }).click()
  await expect(related.getByRole('listitem')).toHaveCount(5)
  await expect(linkPages.getByRole('button',{ name: 'More links' })).toBeDisabled()
  await linkPages.getByRole('button',{ name: 'Previous links' }).click()
  await expect(related.getByRole('listitem')).toHaveCount(20)
  await page.getByRole('button',{ name: 'Back to operations',exact: true }).click()
  await page.getByRole('button',{ name: 'Stock',exact: true }).click()
  await page.getByRole('button',{ name: new RegExp(`^${code} ·`) }).click()
  const ledger=page.getByRole('list',{ name: 'Stock ledger events' })
  await expect(ledger.getByRole('listitem')).toHaveCount(100)
  await expect(ledger).toContainText(`Event ${events.data[0]!.id} ·`)
  await expect(page.getByRole('img',{ name: `Code 39 barcode ${code}`,exact: true })).toBeVisible()
  await expect(page.getByRole('button',{ name: 'Print lot label',exact: true })).toBeVisible()
  const pages=page.getByRole('navigation',{ name: 'Stock ledger pages' })
  await expect(pages.getByRole('button',{ name: 'Newer events' })).toBeDisabled()
  await pages.getByRole('button',{ name: 'Older events' }).click()
  await expect(ledger.getByRole('listitem')).toHaveCount(3)
  await expect(ledger).toContainText(`Event ${events.data[102]!.id} ·`)
  await expect(pages.getByRole('button',{ name: 'Older events' })).toBeDisabled()
  await pages.getByRole('button',{ name: 'Newer events' }).click()
  await expect(ledger.getByRole('listitem')).toHaveCount(100)
  await expect(ledger).toContainText(`Event ${events.data[0]!.id} ·`)
})

test('installed-app shell survives a real offline reload without caching backend records', async ({ page,context }) => {
  await authenticateSampleUser(page)
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  // A prompt-mode worker controls subsequent visits after its initial activation.
  await page.reload()
  await page.waitForFunction(() => navigator.serviceWorker.controller!==null)
  const manifestUrl=await page.locator('link[rel="manifest"]').getAttribute('href')
  const manifest=await (await page.request.get(manifestUrl!)).json() as { display: string;start_url: string;icons: unknown[] }
  expect(manifest.display).toBe('standalone');expect(manifest.start_url).toBe('/');expect(manifest.icons.length).toBeGreaterThan(0)
  const cached=await page.evaluate(async () => {
    const requests=await Promise.all((await caches.keys()).map(async (name) => (await (await caches.open(name)).keys()).map((request) => request.url)))
    return requests.flat()
  })
  expect(cached.some((url) => url.includes('/assets/'))).toBe(true)
  expect(cached.some((url) => /\/rest\/v1\/|\/auth\/v1\/|\/storage\/v1\//.test(url))).toBe(false)
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading',{ name: 'Fasteners Factory ERP',exact: true })).toBeVisible()
  await expect(page.getByText('Offline — read-only shell',{ exact: true })).toBeVisible()
  await page.getByRole('button',{ name: 'Stock',exact: true }).click()
  await expect(page.getByRole('button',{ name: 'Record receipt',exact: true })).toBeDisabled()
  await context.setOffline(false)
  await page.reload()
  await expect(page.getByLabel('Active company')).not.toHaveValue('')
  await expect(page.getByText('Online',{ exact: true })).toBeVisible()
})
