import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function createSolo(page: Page) {
  await page.addInitScript(() => localStorage.setItem('factory-workspace-mode', 'solo'))
  await page.goto('/')
  await expect(page.getByText('Device owner · Solo workspace')).toBeVisible({ timeout: 30_000 })
  await page.getByRole('textbox', { name: 'Company name' }).fill('SAMPLE Solo Factory')
  await page.getByRole('textbox', { name: 'Plant name' }).fill('SAMPLE Solo Plant')
  await page.getByRole('button', { name: /create.*company|create.*factory/i }).click()
  await expect(page.getByRole('combobox', { name: 'Active company' })).toHaveValue(/.+/)
}

test('solo creates a persistent SQLite workspace without contacting Supabase', async ({ page, context }) => {
  const cloudRequests: string[] = []
  page.on('request', (request) => { if (/supabase\.(co|in)|127\.0\.0\.1:54321/.test(request.url())) cloudRequests.push(request.url()) })
  await page.addInitScript(() => localStorage.setItem('factory-workspace-mode', 'solo'))
  await page.goto('/')
  await expect(page.getByText('Device owner · Solo workspace')).toBeVisible({ timeout: 30_000 })
  await expect(page.getByText('Solo — saved on this device')).toBeVisible()
  await page.getByRole('textbox', { name: 'Company name' }).fill('SAMPLE Solo Factory')
  await page.getByRole('textbox', { name: 'Plant name' }).fill('SAMPLE Solo Plant')
  await page.getByRole('button', { name: /create.*company|create.*factory/i }).click()
  await expect(page.getByRole('combobox', {name:'Active company'})).toHaveValue(/.+/)
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('combobox', {name:'Active company'})).toHaveValue(/.+/, { timeout: 30_000 })
  expect(cloudRequests).toEqual([])
})

test('solo commits masters offline and excludes a second writer without losing records', async ({ page, context }) => {
  await createSolo(page)
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Master data', exact: true }).click()
  await page.getByLabel('Customer code', { exact: true }).fill('SAMPLE-OFFLINE')
  await page.getByLabel('Customer name', { exact: true }).fill('SAMPLE Offline Customer')
  await page.getByRole('button', { name: 'Create customer', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Customer created.' })).toBeVisible()
  const second = await context.newPage()
  await second.goto('/')
  await expect(second.getByRole('alert')).toContainText('LOCAL_WORKSPACE_OPEN_IN_ANOTHER_TAB')
  await page.close()
  await second.reload()
  await expect(second.getByText('Device owner · Solo workspace')).toBeVisible()
  await second.getByRole('button', { name: 'Sales orders', exact: true }).click()
  await expect(second.getByLabel('Customer', { exact: true })).toContainText('SAMPLE Offline Customer')
})

test('solo encrypted restore verifies before activation and keeps the original workspace', async ({ page }) => {
  await createSolo(page)
  await page.getByRole('button', { name: 'Data transfer', exact: true }).click()
  const panel = page.getByRole('region', { name: 'Solo backup and move' })
  await panel.getByLabel('Backup passphrase').fill('SAMPLE recovery passphrase')
  const downloaded = page.waitForEvent('download')
  await panel.getByRole('button', { name: 'Download encrypted solo backup' }).click()
  const download = await downloaded, path = await download.path()
  const bytes = await readFile(path!)
  expect(bytes.subarray(0, 8).toString()).toBe('FFERPS01')
  expect(bytes.includes(Buffer.from('SAMPLE Solo Factory'))).toBe(false)
  await panel.getByLabel('Backup passphrase').fill('SAMPLE incorrect passphrase')
  await panel.getByLabel('Verify a solo backup').setInputFiles({ name: 'sample-backup.fferp', mimeType: 'application/octet-stream', buffer: bytes })
  await expect(panel.getByRole('status')).toContainText('Backup authentication failed')
  await expect(panel.getByRole('button', { name: 'Activate verified restored workspace' })).toHaveCount(0)
  await panel.getByLabel('Backup passphrase').fill('SAMPLE recovery passphrase')
  await panel.getByLabel('Verify a solo backup').setInputFiles({ name: 'sample-backup.fferp', mimeType: 'application/octet-stream', buffer: bytes })
  await expect(panel.getByRole('status')).toContainText('Backup verified in a separate SQLite file', { timeout: 30_000 })
  await panel.getByRole('button', { name: 'Activate verified restored workspace' }).click()
  await expect(page.getByRole('combobox', { name: 'Active company' })).toHaveValue(/.+/)
  await page.getByRole('button', { name: 'Data transfer', exact: true }).click()
  await page.getByLabel('Open retained workspace').selectOption('original')
  await expect(page.getByRole('combobox', { name: 'Active company' })).toHaveValue(/.+/)
})
